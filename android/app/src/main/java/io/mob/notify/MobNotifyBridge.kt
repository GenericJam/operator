// mob_notify plugin — Android bridge (local notifications via AlarmManager,
// push registration and receipt via FirebaseMessaging).
//
// Extracted from mob-core's MobBridge notify_schedule / notify_cancel /
// notify_register_push (MobBridge.kt.eex ~1379-1444 pre-strip). Local
// notification DELIVERY stays in the host: its NotificationReceiver displays
// the scheduled notification and the tap routes through MainActivity. Push
// receipt ships HERE (MOB-327): MobFirebaseService (token refresh, messages
// that reach the app) and MobNotifyFcm (taps on notifications the system
// tray showed for FCM itself). The shared state lives in
// io.mob.plugin.MobNotifyHub (GENERATED by mob_dev next to MobActivityAware)
// — the stable seam both sides can reference, since this bridge can't name
// host-package classes and the host can't name plugin packages without
// breaking plugin-less builds.
//
// HOST-CLASS NAME ASSUMPTION: the alarm intent targets
// "<applicationId>.NotificationReceiver" via setClassName — true for every
// mob_new-generated app (the Kotlin package IS the applicationId). A host
// with a divergent package must keep its receiver at that name.
//
// BOOT RE-ARM: AlarmManager alarms are wiped on reboot, so scheduled
// notifications silently vanish. notify_schedule persists each schedule to
// SharedPreferences (via MobNotifySchedules), and MobNotifyBootReceiver
// re-arms every still-future entry on ACTION_BOOT_COMPLETED. The shared arm +
// persist + read logic lives in the MobNotifySchedules object so the bridge
// (which has an Activity) and the boot receiver (which has only a Context)
// arm identically — every helper takes a Context.
//
// SINGLE-FILE LAYOUT: MobNotifySchedules, MobNotifyBootReceiver, MobNotifyFcm,
// MobFcmEnvelope and MobFirebaseService are declared in THIS file rather than
// separate .kt files because mob_dev copies exactly the one `android.bridge_kt`
// path into the host Kotlin sourceSet (and the plugin signer only signs that
// one path) — sibling files wouldn't be compiled or signed. Kotlin allows
// multiple top-level declarations per file, so they all ship together under
// the declared bridge_kt; the plugin manifest's
// android.manifest_application_snippets declares the receiver and service.
